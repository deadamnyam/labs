# Считываем первую строку (s) — это ДНК-последовательность, в которой ищем мотив.
# strip() убирает лишние пробелы и символы переноса строки, если они есть.
s = input().strip()

# Считываем вторую строку (t) — это мотив (подстрока), которую ищем в s.
t = input().strip()

# Создаём пустой список positions, чтобы хранить начальные позиции всех найденных вхождений t в s.
positions = []

# Находим первое вхождение подстроки t в s с помощью метода .find().
# Если t не найдена, .find() вернёт -1.
index = s.find(t)

# Запускаем цикл while, который работает, пока index не равен -1 (т.е. пока находятся вхождения t).
while index != -1:
    # Добавляем в список positions текущую позицию (index), 
    # потому что в биологии принята 1-индексация (первый символ = 1, а не 0).
    positions.append(index)

    # Ищем следующее вхождение t в s, начиная с позиции (index + 1), 
    # чтобы не находить одно и то же вхождение бесконечно.
    index = s.find(t, index + 1)

# Выводим результат: преобразуем числа в списке positions в строки и объединяем их через пробел.
print(' '.join(map(str, positions)))